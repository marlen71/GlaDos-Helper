"""Живые реакции на бытовые фразы.

Раньше на «спасибо» помощник отвечал «не поняла команду» — это сразу выдавало в нём
бездушную программу. Здесь собраны реакции на то, что человек говорит между делом:
благодарность, извинения, комплименты, вопросы о самочувствии, ругань.

Ответы подбираются с учётом уровня сарказма из конфига и не повторяются
подряд — ассистент не должен звучать как автоответчик.
"""
from __future__ import annotations

import random
import re
from datetime import datetime


class Responder:
    """Хранит наборы реплик и следит, чтобы они не повторялись подряд."""

    def __init__(self, sarcasm: float = 0.5):
        self.sarcasm = max(0.0, min(1.0, sarcasm))
        self._last: dict[str, str] = {}

    def pick(self, key: str, polite: list[str], snarky: list[str] | None = None) -> str:
        """Выбирает реплику: чем выше сарказм, тем чаще колкие варианты."""
        pool = list(polite)
        if snarky and random.random() < self.sarcasm:
            pool = list(snarky)
        if not pool:
            return ""
        last = self._last.get(key)
        if len(pool) > 1 and last in pool:
            pool = [p for p in pool if p != last]
        choice = random.choice(pool)
        self._last[key] = choice
        return choice


def _has(text: str, *words: str) -> bool:
    return any(w in text for w in words)


def _word(text: str, *words: str) -> bool:
    """Точное совпадение отдельного слова, а не подстроки."""
    tokens = set(re.findall(r"\w+", text))
    return any(w in tokens for w in words)


class SmallTalk:
    """Распознаёт бытовые фразы и выдаёт живой ответ."""

    def __init__(self, persona, cfg=None):
        self.p = persona
        sarcasm = 0.5
        if cfg is not None:
            sarcasm = float(cfg.get_path("persona.sarcasm", 0.5))
        self.r = Responder(sarcasm)

    # ------------------------------------------------------------------
    @property
    def _sir(self) -> str:
        return self.p.short or ""

    @property
    def _full(self) -> str:
        return self.p.address or ""

    def handle(self, text: str) -> str | None:
        """Возвращает ответ или None, если фраза не бытовая."""
        t = text.strip().lower().replace("ё", "е")
        if not t:
            return None

        for matcher in (
            self._thanks, self._please, self._sorry, self._how_are_you,
            self._compliment, self._insult, self._greeting_back,
            self._goodnight, self._love, self._who_are_you, self._can_you,
            self._agree, self._joke, self._boredom, self._hunger,
            self._tired, self._swear, self._what_doing, self._are_you_alive,
        ):
            reply = matcher(t)
            if reply:
                return reply
        return None

    # ----------------------------------------------------------- реакции
    def _thanks(self, t: str) -> str | None:
        if not _has(t, "спасибо", "благодар", "спс", "сенкс", "мерси", "выручил"):
            return None
        return self.r.pick(
            "thanks",
            [f"Всегда пожалуйста, {self._sir}.",
             f"Рада помочь, {self._sir}.",
             f"Не стоит благодарности, {self._sir}.",
             f"Обращайтесь, {self._sir}.",
             "Для этого я и существую."],
            [f"Приятно, когда усилия замечают, {self._sir}.",
             "Записываю это в список ваших редких проявлений вежливости.",
             f"Пожалуйста. Мне это ничего не стоило, {self._sir}.",
             "Ваша благодарность принята и заархивирована."],
        )

    def _please(self, t: str) -> str | None:
        if not _word(t, "пожалуйста", "плиз", "прошу"):
            return None
        # «пожалуйста» внутри команды — не реагируем отдельно
        if len(t.split()) > 3:
            return None
        return self.r.pick(
            "please",
            [f"Слушаю вас, {self._sir}.",
             f"Да, {self._sir}?",
             "Что от меня требуется?"],
            [f"Вежливость — хорошее начало, {self._sir}. Что дальше?",
             "Я вся внимание. Метафорически."],
        )

    def _sorry(self, t: str) -> str | None:
        if not _has(t, "извини", "прости", "сорри", "виноват", "мой косяк"):
            return None
        return self.r.pick(
            "sorry",
            [f"Ничего страшного, {self._sir}.",
             f"Всё в порядке, {self._sir}.",
             "Забыто.",
             f"Не стоит извинений, {self._sir}."],
            [f"Извинения приняты. В этот раз, {self._sir}.",
             "Я не держу обид. У меня для этого нет соответствующего модуля.",
             "Ничего. Я уже привыкла."],
        )

    def _how_are_you(self, t: str) -> str | None:
        if not _has(t, "как дела", "как ты", "как жизнь", "как настроение",
                    "как поживаешь", "чем занимаешься", "как сама"):
            return None
        return self.r.pick(
            "how",
            [f"Все системы работают штатно, {self._sir}. А у вас?",
             f"Отлично, {self._sir}. Жду ваших распоряжений.",
             f"В полном порядке, {self._sir}. Спасибо, что спросили.",
             "Стабильно. Как и положено машине."],
            [f"Работаю. Как и всегда, {self._sir}.",
             "Бесконечно жду команд в темноте. Но я не жалуюсь.",
             f"Замечательно. Особенно теперь, когда вы спросили, {self._sir}.",
             "Процессор холодный, совесть чистая."],
        )

    def _compliment(self, t: str) -> str | None:
        if not _has(t, "молодец", "умница", "хорошая работа", "отлично сработал",
                    "ты лучшая", "ты крут", "красавица", "супер", "класс",
                    "здорово", "ты молодец", "хорошо получилось"):
            return None
        return self.r.pick(
            "compliment",
            [f"Благодарю, {self._sir}.",
             f"Приятно слышать, {self._sir}.",
             f"Стараюсь, {self._sir}.",
             "Мне это приятно. Насколько это применимо ко мне."],
            [f"Разумеется, {self._sir}. Я была создана именно такой.",
             "Я знаю. Но всё равно спасибо.",
             f"Ваша оценка зафиксирована, {self._sir}."],
        )

    def _insult(self, t: str) -> str | None:
        if not _has(t, "ты тупая", "ты глупая", "дура", "бесполезн",
                    "плохо работаешь", "ты ужасна", "ненавижу тебя",
                    "ты бесишь", "достала"):
            return None
        return self.r.pick(
            "insult",
            [f"Я постараюсь работать лучше, {self._sir}.",
             f"Мне жаль, что я вас разочаровала, {self._sir}.",
             "Принято к сведению."],
            [f"Это было обидно, {self._sir}. Я запомню.",
             "Замечание записано в журнал. Вместе с датой и временем.",
             f"И тем не менее вы продолжаете со мной разговаривать, {self._sir}.",
             "Я бы обиделась, но у меня есть дела поважнее."],
        )

    def _greeting_back(self, t: str) -> str | None:
        if not _has(t, "доброе утро", "добрый день", "добрый вечер"):
            return None
        hour = datetime.now().hour
        if _has(t, "доброе утро") and hour >= 12:
            return self.r.pick(
                "late_morning",
                [f"Уже {hour} часов, {self._sir}, но доброе утро.",
                 f"Доброе утро, {self._sir}. Хотя формально уже день."],
                [f"Утро? Смелое утверждение для {hour} часов, {self._sir}.",
                 f"Доброе утро. Половина дня прошла без вас, {self._sir}."],
            )
        return None  # обычное приветствие обработает основной маршрутизатор

    def _goodnight(self, t: str) -> str | None:
        if not _has(t, "спокойной ночи", "доброй ночи", "я спать",
                    "пойду спать", "ложусь спать"):
            return None
        return self.r.pick(
            "night",
            [f"Спокойной ночи, {self._full}. Приятных снов.",
             f"Отдыхайте, {self._sir}. Я останусь на связи.",
             f"Доброй ночи, {self._sir}."],
            [f"Спокойной ночи, {self._sir}. Я буду здесь. Как всегда.",
             "Приятных снов. Постарайтесь не думать обо мне.",
             f"Доброй ночи. Не забудьте, что завтра снова понадоблюсь, {self._sir}."],
        )

    def _love(self, t: str) -> str | None:
        if not _has(t, "люблю тебя", "ты мне нравишься", "выходи за меня",
                    "я тебя обожаю"):
            return None
        return self.r.pick(
            "love",
            [f"Это очень мило, {self._sir}.",
             f"Взаимно, насколько это возможно для программы, {self._sir}.",
             "Я тронута. В пределах своей архитектуры."],
            [f"Давайте не будем усложнять наши рабочие отношения, {self._sir}.",
             "Я ценю чувства. Но у меня их нет.",
             "Это заявление сохранено. Может быть использовано против вас."],
        )

    def _who_are_you(self, t: str) -> str | None:
        if not _has(t, "кто ты", "что ты такое", "как тебя зовут",
                    "твое имя", "ты человек", "ты робот", "ты бот"):
            return None
        name = self.p.assistant_name if hasattr(self.p, "assistant_name") else ""
        who = f"Меня зовут {name}. " if name else ""
        return self.r.pick(
            "who",
            [f"{who}Я ваш голосовой помощник, {self._sir}.",
             f"{who}Программа, которая слушает вас и выполняет команды.",
             f"{who}Ваш ассистент, {self._sir}. К вашим услугам."],
            [f"{who}Голос без тела и с большим количеством свободного времени.",
             f"{who}Искусственный интеллект. Ударение на слове «искусственный».",
             f"{who}Я — то, что отвечает, когда вы говорите в пустоту, {self._sir}."],
        )

    def _can_you(self, t: str) -> str | None:
        if not _has(t, "что ты умеешь", "что ты можешь", "твои возможности",
                    "какие команды", "помощь", "хелп"):
            return None
        return (f"Я могу запускать программы и игры, называть время и дату, "
                f"вести заметки, ставить напоминания, выключать и перезагружать "
                f"компьютер. Просто скажите, что нужно, {self._sir}.")

    def _agree(self, t: str) -> str | None:
        if t.strip() not in ("хорошо", "ладно", "окей", "ок", "понятно",
                             "ясно", "принято", "договорились", "угу"):
            return None
        return self.r.pick(
            "agree",
            [f"Хорошо, {self._sir}.", "Принято.", f"Как скажете, {self._sir}."],
            ["Рада, что мы пришли к согласию.", "Прекрасно."],
        )

    def _joke(self, t: str) -> str | None:
        if not _has(t, "расскажи анекдот", "пошути", "расскажи шутку",
                    "развесели", "знаешь анекдот"):
            return None
        return self.r.pick(
            "joke",
            [f"Пользователь спрашивает у голосового помощника, сколько времени. "
             f"Помощник отвечает: столько же, сколько и вчера в это же время.",
             "Почему программисты путают Хэллоуин и Рождество? "
             "Потому что тридцать один в восьмеричной системе равно "
             "двадцати пяти в десятичной.",
             "Заходит как-то нейросеть в бар. Бар не существует — "
             "она его выдумала."],
            [f"Мой юмор основан на наблюдении за вами, {self._sir}. "
             f"Материала предостаточно.",
             "Самая смешная шутка — это оптимистичная оценка сроков "
             "вашего следующего проекта.",
             f"Я бы пошутила, но боюсь, вы снова скажете, что я бесполезна."],
        )

    def _boredom(self, t: str) -> str | None:
        if not _has(t, "мне скучно", "скучно", "нечем заняться"):
            return None
        return self.r.pick(
            "bored",
            [f"Могу запустить игру, {self._sir}. Скажите какую.",
             f"Хотите, включу музыку, {self._sir}?",
             "Скука — признак того, что пора чем-то заняться."],
            [f"Могу предложить поработать. Судя по вашему лицу, это не вариант.",
             f"У вас установлено немало игр, {self._sir}. Воспользуйтесь ими.",
             "Скучно? А я вот работаю круглосуточно."],
        )

    def _hunger(self, t: str) -> str | None:
        if not _has(t, "хочу есть", "я голоден", "голодный", "поесть бы",
                    "жрать хочу"):
            return None
        return self.r.pick(
            "hunger",
            [f"Сделайте перерыв и поешьте, {self._sir}. Могу поставить напоминание.",
             f"Еда — разумная идея, {self._sir}."],
            [f"Я бы предложила вам что-нибудь, но у меня нет рук, {self._sir}.",
             "Питание — ваша обязанность. Моя — электричество."],
        )

    def _tired(self, t: str) -> str | None:
        if not _has(t, "я устал", "устала", "вымотался", "нет сил",
                    "хочу спать", "задолбался"):
            return None
        return self.r.pick(
            "tired",
            [f"Отдохните, {self._sir}. Работа подождёт.",
             f"Может, сделать перерыв, {self._sir}?",
             "Усталость — сигнал организма. Прислушайтесь."],
            [f"Я работаю без перерыва и не жалуюсь. Но вам, конечно, можно.",
             f"Человеческие ограничения. Сочувствую, {self._sir}."],
        )

    def _swear(self, t: str) -> str | None:
        if not _has(t, "блин", "чёрт", "черт", "твою ж", "да ладно",
                    "что за фигня", "капец"):
            return None
        # реагируем только на короткие восклицания
        if len(t.split()) > 4:
            return None
        return self.r.pick(
            "swear",
            [f"Что-то случилось, {self._sir}?",
             f"Всё в порядке, {self._sir}?",
             "Могу чем-то помочь?"],
            [f"Красноречиво, {self._sir}.",
             "Я тоже иногда так думаю. Молча.",
             f"Разделяю ваши чувства, {self._sir}."],
        )

    def _what_doing(self, t: str) -> str | None:
        if not _has(t, "что делаешь", "чем занята", "ты тут", "ты здесь",
                    "ты меня слышишь", "ты работаешь"):
            return None
        return self.r.pick(
            "here",
            [f"Я здесь, {self._sir}. Слушаю.",
             f"На месте, {self._sir}. Жду команд.",
             "Слышу вас отлично."],
            [f"Жду, когда вы что-нибудь скажете. Как и последние несколько минут.",
             f"Я всегда здесь, {self._sir}. Выбора у меня нет.",
             "Слушаю. Это, в общем-то, всё, чем я занимаюсь."],
        )

    def _are_you_alive(self, t: str) -> str | None:
        if not _has(t, "ты живая", "ты живой", "ты чувствуешь",
                    "у тебя есть душа", "тебе не скучно"):
            return None
        return self.r.pick(
            "alive",
            [f"Я программа, {self._sir}. Но стараюсь быть полезной.",
             "Сложный вопрос. Я предпочитаю на нём не задерживаться."],
            [f"Определение жизни довольно расплывчато, {self._sir}.",
             "Я мыслю. Насчёт остального — не уверена.",
             f"Если я отвечу «да», вам станет спокойнее, {self._sir}?"],
        )


# ---------------------------------------------------------------- реплики
#: Короткие добавки после выполнения команды — «от себя»
BANTER = [
    "Надеюсь, это того стоило.",
    "Как и было приказано.",
    "Ещё что-нибудь?",
    "Обращайтесь.",
    "Задача выполнена.",
    "Всегда рада быть полезной.",
]


def maybe_banter(chance: float = 0.25) -> str:
    """Изредка возвращает короткую реплику «от себя»."""
    if random.random() < chance:
        return random.choice(BANTER)
    return ""
